// Builds a self-hosted Font Awesome subset containing only the icons the site
// actually uses, instead of loading the full ~100 KB stylesheet (and ~300 KB of
// fonts) from a CDN on every page.
//
// It scans app/**/*.{ts,tsx} for `fa-<name>` class names, subsets the Font
// Awesome Free webfonts to those glyphs, and writes app/styles/icons/:
//   icons.css          @font-face + base classes + one ::before rule per icon
//   fa-*.woff2         subset fonts (only the families in use)
//
// Runs automatically before `npm run dev` and `npm run build`. Run it by hand
// with `npm run icons` after adding a new <i className="fa-solid fa-…" />.
//
// The generated files are committed. If generation fails (for example when dev
// dependencies aren't installed), the committed files are kept and the build
// continues with a warning instead of failing.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const srcDir = path.join(root, "app");
const outDir = path.join(root, "app/styles/icons");

const FAMILIES = {
  solid: { font: "Font Awesome 6 Free", weight: 900, file: "fa-solid-900.woff2" },
  regular: { font: "Font Awesome 6 Free", weight: 400, file: "fa-regular-400.woff2" },
  brands: { font: "Font Awesome 6 Brands", weight: 400, file: "fa-brands-400.woff2" },
};
// Utility classes that start with "fa-" but aren't icons.
const NON_ICON_CLASSES = new Set(Object.keys(FAMILIES));

const byName = (a, b) => a.localeCompare(b, "en");

function sourceFiles(dir) {
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...sourceFiles(full));
    else if (/\.(tsx?|jsx?)$/.test(entry.name)) files.push(full);
  }
  return files;
}

/** Map every icon name and alias to { name, unicode, free: [styles] }. */
function loadIconMetadata() {
  const faPkgJson = require.resolve("@fortawesome/fontawesome-free/package.json");
  const { version } = JSON.parse(fs.readFileSync(faPkgJson, "utf8"));
  const metadata = JSON.parse(
    fs.readFileSync(path.join(path.dirname(faPkgJson), "metadata/icon-families.json"), "utf8")
  );
  const entry = (name, icon) => ({
    name,
    unicode: icon.unicode,
    free: (icon.familyStylesByLicense?.free ?? [])
      .filter((style) => style.family === "classic")
      .map((style) => style.style),
  });
  const icons = new Map();
  for (const [name, icon] of Object.entries(metadata)) icons.set(name, entry(name, icon));
  for (const [name, icon] of Object.entries(metadata)) {
    for (const alias of icon.aliases?.names ?? []) {
      if (!icons.has(alias)) icons.set(alias, entry(name, icon));
    }
  }
  return { version, icons };
}

function buildCss(version, families, classNames, iconsByName) {
  const fontFaces = families.map(
    (f) => `@font-face {
  font-family: "${FAMILIES[f].font}";
  font-style: normal;
  font-weight: ${FAMILIES[f].weight};
  font-display: block;
  src: url("./${FAMILIES[f].file}") format("woff2");
}`
  );
  const familyRules = families.map(
    (f) => `.fa-${f} {
  font-family: "${FAMILIES[f].font}", sans-serif;
  font-weight: ${FAMILIES[f].weight};
}`
  );
  const iconRules = classNames.map(
    (className) => `.fa-${className}::before {\n  content: "\\${iconsByName.get(className).unicode}";\n}`
  );
  return `/*! Generated by scripts/icons.mjs — do not edit; run \`npm run icons\`.
 * Font Awesome Free ${version} by @fontawesome - https://fontawesome.com
 * License - https://fontawesome.com/license/free (Icons: CC BY 4.0, Fonts: SIL OFL 1.1, Code: MIT License)
 * Subset to the ${classNames.length} icons used in app/. */
${fontFaces.join("\n")}
${families.map((f) => `.fa-${f}`).join(",\n")} {
  -moz-osx-font-smoothing: grayscale;
  -webkit-font-smoothing: antialiased;
  display: var(--fa-display, inline-block);
  font-style: normal;
  font-variant: normal;
  line-height: 1;
  text-rendering: auto;
}
${familyRules.join("\n")}
${iconRules.join("\n")}
`;
}

/** Every `fa-<name>` class used in app/, excluding the family classes. */
function findUsedClassNames() {
  const used = new Set();
  for (const file of sourceFiles(srcDir)) {
    for (const match of fs.readFileSync(file, "utf8").matchAll(/\bfa-([a-z0-9-]+)/g)) {
      if (!NON_ICON_CLASSES.has(match[1])) used.add(match[1]);
    }
  }
  return used;
}

/**
 * Glyph names to keep per font family. Every family an icon exists in gets the
 * glyph, so `fa-regular fa-star` and `fa-solid fa-star` both work without
 * tracking which prefix each usage has.
 */
function groupGlyphsByFamily(classNames, iconsByName) {
  const glyphsByFamily = {};
  for (const className of classNames) {
    const icon = iconsByName.get(className);
    for (const family of icon.free.filter((f) => FAMILIES[f])) {
      glyphsByFamily[family] ??= new Set();
      glyphsByFamily[family].add(icon.name);
    }
  }
  const families = Object.keys(FAMILIES).filter((f) => glyphsByFamily[f]);
  const subset = Object.fromEntries(families.map((f) => [f, [...glyphsByFamily[f]].sort(byName)]));
  return { families, subset };
}

/**
 * Generate fonts and CSS into a temp directory, then replace the committed
 * output only once everything succeeded.
 */
async function writeSubset(subset, families, css) {
  const { fontawesomeSubset } = await import("fontawesome-subset");
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "fa-subset-"));
  try {
    const ok = await fontawesomeSubset(subset, tmpDir, { package: "free", targetFormats: ["woff2"] });
    if (ok === false) throw new Error("fontawesome-subset reported a failure");
    const missing = families.find((f) => !fs.existsSync(path.join(tmpDir, FAMILIES[f].file)));
    if (missing) throw new Error(`fontawesome-subset did not write ${FAMILIES[missing].file}`);
    fs.writeFileSync(path.join(tmpDir, "icons.css"), css);

    fs.rmSync(outDir, { recursive: true, force: true });
    fs.mkdirSync(outDir, { recursive: true });
    for (const file of fs.readdirSync(tmpDir)) {
      fs.copyFileSync(path.join(tmpDir, file), path.join(outDir, file));
    }
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
}

async function main() {
  const { version, icons: iconsByName } = loadIconMetadata();
  const used = [...findUsedClassNames()];

  const unknown = used.filter((name) => !iconsByName.has(name));
  if (unknown.length) {
    console.warn(`⚠️  Not Font Awesome Free ${version} icons, skipped: ${unknown.join(", ")}`);
  }
  const classNames = used.filter((name) => iconsByName.has(name)).sort(byName);
  const { families, subset } = groupGlyphsByFamily(classNames, iconsByName);

  await writeSubset(subset, families, buildCss(version, families, classNames, iconsByName));

  const fontBytes = fs
    .readdirSync(outDir)
    .filter((f) => f.endsWith(".woff2"))
    .reduce((sum, f) => sum + fs.statSync(path.join(outDir, f)).size, 0);
  console.log(
    `✅ Icons subset: ${classNames.length} icons in ${families.join(", ")} (${(fontBytes / 1024).toFixed(1)} KB of fonts)`
  );
}

try {
  await main();
} catch (error) {
  if (fs.existsSync(path.join(outDir, "icons.css"))) {
    console.warn(
      `⚠️  Could not regenerate the Font Awesome subset; keeping the committed files in app/styles/icons.\n   ${error.message}`
    );
  } else {
    console.error("❌ Could not generate the Font Awesome subset:", error);
    process.exit(1);
  }
}
